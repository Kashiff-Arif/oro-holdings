        $(document).on("click", ".card", function () {
    const $modal = $(this)
        .closest(".swiper-slide")
        .find(".card-modal");

    // Save original parent
    $modal.data("original-parent", $modal.parent());

    // Move modal to body
    $("body").append($modal);

    // Open
    $modal.addClass("is-open");
    $("body").addClass("modal-open");
});


// Close icon
$(document).on("click", ".card-modal__close", function (e) {
    e.preventDefault();

    closeModal($(this).closest(".card-modal"));
});


// Backdrop click
$(document).on("click", ".card-modal", function (e) {
    if (e.target === this) {
        closeModal($(this));
    }
});


function closeModal($modal) {
    $modal.removeClass("is-open");
    $("body").removeClass("modal-open");

    // Get original slide
    const $originalParent = $modal.data("original-parent");

    // Put modal back inside its original slide
    if ($originalParent && $originalParent.length) {
        $originalParent.append($modal);
    }
}

