        this.classList.remove("is-dragover");
    });

    cvUploadBox.addEventListener("drop", function (e) {
        e.preventDefault();

        this.classList.remove("is-dragover");

        const file = e.dataTransfer.files[0];

        if (file) {
            cvFile.files = e.dataTransfer.files;
            showSelectedFile(file);
        }
    });

    function showSelectedFile(file) {
        const maxSize = 5 * 1024 * 1024;
        const allowedTypes = [
            "application/pdf",
            "application/msword",
            "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
        ];

        if (!allowedTypes.includes(file.type)) {
            alert("Please upload a PDF or DOC/DOCX file.");
            cvFile.value = "";
            return;
        }

        if (file.size > maxSize) {
            alert("File size must be less than 5MB.");
            cvFile.value = "";
            return;
        }

        cvUploadBox.querySelector(".cv-upload__text p").innerHTML =
            `<strong>${file.name}</strong>`;

        cvUploadBox.querySelector(".cv-upload__text span").textContent =
            "File selected successfully";
    }
